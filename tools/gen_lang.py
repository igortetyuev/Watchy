# Generates include/lang_strings.h from lib/Watchy/lang/<LANG>.json.
# LANG is read from $PROJECT_DIR/.env (KEY=VALUE, same format as load_env.py),
# default "en". The header is only rewritten when its content changes, to keep
# the mtime stable and avoid pointless recompiles.
import json
import os
import sys
Import("env")

# __file__ is not defined inside SCons script context; the lang files live
# next to this script in the Watchy library under the project's lib dir
project_dir = env.subst("$PROJECT_DIR")
lang_dir = os.path.join(project_dir, "lib", "Watchy", "lang")

lang = "en"
env_path = os.path.join(project_dir, ".env")
if os.path.isfile(env_path):
    with open(env_path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = (s.strip() for s in line.split("=", 1))
            if key == "LANG":
                if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                    value = value[1:-1]
                lang = value

ref_path = os.path.join(lang_dir, "en.json")
lang_path = os.path.join(lang_dir, lang + ".json")
if not os.path.isfile(lang_path):
    available = sorted(os.path.splitext(f)[0]
                       for f in os.listdir(lang_dir) if f.endswith(".json"))
    sys.exit("gen_lang.py: unknown LANG=%s, available: %s" % (lang, " ".join(available)))

with open(ref_path) as f:
    ref = json.load(f)
with open(lang_path) as f:
    data = json.load(f)

ref_keys = [k for k in ref if not k.startswith("_")]
lang_keys = [k for k in data if not k.startswith("_")]
missing = [k for k in ref_keys if k not in lang_keys]
extra = [k for k in lang_keys if k not in ref_keys]
if missing or extra:
    sys.exit("gen_lang.py: %s.json keys do not match en.json, missing: %s, extra: %s"
             % (lang, ", ".join(missing) or "-", ", ".join(extra) or "-"))

def c_escape(s):
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t"))

charset = data.get("_charset", "latin1")
lines = []
lines.append("// Generated by lib/Watchy/tools/gen_lang.py from lang/%s.json. Do not edit." % lang)
lines.append("#pragma once")
lines.append("#include <stdint.h>")
lines.append('#define LANG_CODE "%s"' % lang)
if charset == "cyrillic":
    lines.append("#define LANG_CHARSET_CYRILLIC 1")
else:
    lines.append("#define LANG_CHARSET_LATIN1 1")
lines.append("")
lines.append("enum StrId : uint8_t {")
for k in ref_keys:
    lines.append("  S_%s," % k.upper())
lines.append("  S__COUNT")
lines.append("};")
lines.append("")
lines.append("static const char *const STR[S__COUNT] = {")
for k in ref_keys:
    lines.append('  "%s", // %s' % (c_escape(data[k]), k))
lines.append("};")
lines.append("")
out = "\n".join(lines)

out_dir = os.path.join(project_dir, "include")
if not os.path.isdir(out_dir):
    os.makedirs(out_dir)
out_path = os.path.join(out_dir, "lang_strings.h")
old = None
if os.path.isfile(out_path):
    with open(out_path) as f:
        old = f.read()
if old != out:
    with open(out_path, "w") as f:
        f.write(out)

print("gen_lang.py: LANG=%s (%s), %d strings" % (lang, charset, len(ref_keys)))
